export const cleanDanishWord = (raw: string): string => {
  return raw
    .toLowerCase()
    .replace(/^[^\wæøåÆØÅéÉ0-9]+|[^\wæøåÆØÅéÉ0-9]+$/g, '')
    .trim();
};

